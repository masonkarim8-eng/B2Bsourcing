// Builds the chatbot's knowledge file from the public catalog, so the assistant
// can only quote what customer pages already show. Runs after `vite build`.
import { writeFileSync } from 'node:fs';
import { publicProducts } from '../src/public-products.js';
import { getDisclosure } from '../src/disclosure.js';

const lines = publicProducts.map((p) => {
  const tier = getDisclosure(p).tier;
  const access = tier === 'public' ? 'public specs' : tier === 'teaser' ? 'flagship preview, details only via sales review' : 'dealer model, specs only via buyer review';
  const specs = [p.dimensions && `size ${p.dimensions}`, p.moq && `MOQ ${p.moq}`, p.loading && `loading ${p.loading}`].filter(Boolean).join('; ');
  const colors = p.color ? ` | color shown: ${p.color}; other colors: ${p.colorOptions}` : '';
  return `- ${p.model} | ${p.name} | category: ${p.category} | ${access} | ${p.summary} ${p.description}${specs ? ` | ${specs}` : ''}${colors}`;
});
const models = publicProducts.map((p) => p.model);
const categories = [...new Set(publicProducts.map((p) => p.category))];
writeFileSync(new URL('../worker/catalog.generated.js', import.meta.url),
  `// Generated by scripts/build-catalog.mjs. Do not edit.\nexport const CATALOG = ${JSON.stringify(lines.join('\n'))};\nexport const MODELS = ${JSON.stringify(models)};\nexport const CATEGORIES = ${JSON.stringify(categories)};\n`);
console.log(`catalog: ${models.length} models`);
